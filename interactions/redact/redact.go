// A graph describes where sensitive values sit in a body. Node 0 is a
// sentinel for "nothing sensitive below here"; roots are the body schemas.
type graph struct {
	nodes []node
	roots []int
}

type node struct {
	sensitive bool
	// fields maps JSON property names to their schema; a property that is not
	// declared uses values (additional properties or map values).
	fields   map[string]int
	item     int
	values   int
	variants []int
	// plainObject, plainArray, plainString, plainNumber and plainBoolean
	// report union members accepting JSON values of that type and holding
	// nothing sensitive.
	plainObject  bool
	plainArray   bool
	plainString  bool
	plainNumber  bool
	plainBoolean bool
}

type shape int

const (
	objectShape shape = iota
	arrayShape
	stringShape
	numberShape
	booleanShape
)

// redact returns body unchanged when it has nothing to mask. A body that
// cannot be parsed is masked as a whole.
func (g *graph) redact(contentType string, body []byte) []byte {
	if g == nil || len(body) == 0 {
		return body
	}
	if g.sensitive(g.roots) {
		return []byte(Mask)
	}
	mediaType, params, err := mime.ParseMediaType(contentType)
	if err != nil {
		mediaType = strings.ToLower(strings.TrimSpace(strings.SplitN(contentType, ";", 2)[0]))
	}
	var masked []byte
	ok := false
	switch {
	case mediaType == "application/x-www-form-urlencoded":
		masked, _, ok = g.redactForm(body, g.roots)
	case mediaType == "multipart/form-data":
		masked, _, ok = g.redactMultipart(body, params["boundary"], g.roots)
	case mediaType == "" || mediaType == "application/json" || mediaType == "text/json" || strings.HasSuffix(mediaType, "+json"):
		masked, _, ok = g.redactJSON(body, g.roots)
	}
	if !ok {
		return []byte(Mask)
	}
	return masked
}

func (g *graph) redactJSON(body []byte, roots []int) ([]byte, bool, bool) {
	dec := json.NewDecoder(bytes.NewReader(body))
	dec.UseNumber()
	var value any
	if err := dec.Decode(&value); err != nil {
		return nil, false, false
	}
	if _, err := dec.Token(); err != io.EOF {
		return nil, false, false
	}
	// Decoding keeps the last of duplicate keys, so the bytes returned as is
	// could hold an earlier, unmasked one.
	if hasDuplicateKeys(body) {
		return nil, false, false
	}
	masked, changed := g.mask(value, roots, 0)
	if !changed {
		return body, false, true
	}
	var out bytes.Buffer
	enc := json.NewEncoder(&out)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(masked); err != nil {
		return nil, false, false
	}
	return bytes.TrimSuffix(out.Bytes(), []byte("\n")), true, true
}

// redactForm masks the fields of a form body. A field holding a sensitive
// value or array of values is masked, and a JSON-encoded field is masked
// within.
func (g *graph) redactForm(body []byte, roots []int) ([]byte, bool, bool) {
	pairs := strings.Split(string(body), "&")
	changed := false
	for i, pair := range pairs {
		rawKey, rawValue, _ := strings.Cut(pair, "=")
		key, err := url.QueryUnescape(rawKey)
		if err != nil || isJSONStructure([]byte(key)) {
			return nil, false, false
		}
		value, err := url.QueryUnescape(rawValue)
		if err != nil {
			return nil, false, false
		}
		masked, fieldChanged := g.redactValue([]byte(value), g.field(roots, key))
		if !fieldChanged {
			continue
		}
		changed = true
		if string(masked) == Mask {
			pairs[i] = rawKey + "=" + Mask
		} else {
			pairs[i] = rawKey + "=" + url.QueryEscape(string(masked))
		}
	}
	if !changed {
		return body, false, true
	}
	return []byte(strings.Join(pairs, "&")), true, true
}

// redactMultipart masks the parts of a multipart body by part name, keeping
// the boundary and the part headers.
func (g *graph) redactMultipart(body []byte, boundary string, roots []int) ([]byte, bool, bool) {
	if boundary == "" {
		return nil, false, false
	}
	reader := multipart.NewReader(bytes.NewReader(body), boundary)
	var out bytes.Buffer
	writer := multipart.NewWriter(&out)
	if err := writer.SetBoundary(boundary); err != nil {
		return nil, false, false
	}
	changed := false
	for {
		part, err := reader.NextRawPart()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, false, false
		}
		data, err := io.ReadAll(part)
		if err != nil {
			return nil, false, false
		}
		partRoots := g.field(roots, part.FormName())
		masked, partChanged := g.redactValue(data, partRoots)
		if !partChanged && len(g.expand(partRoots)) > 0 && isEncodedPart(part.Header) {
			masked, partChanged = []byte(Mask), true
		}
		changed = changed || partChanged
		header := part.Header
		if partChanged {
			// The mask is written as is, not in the part's transfer encoding,
			// and with its own length.
			header = make(textproto.MIMEHeader, len(part.Header))
			for key, values := range part.Header {
				header[key] = values
			}
			header.Del("Content-Transfer-Encoding")
			header.Del("Content-Encoding")
			header.Del("Content-Length")
		}
		partWriter, err := writer.CreatePart(header)
		if err != nil {
			return nil, false, false
		}
		if _, err := partWriter.Write(masked); err != nil {
			return nil, false, false
		}
	}
	if !changed {
		return body, false, true
	}
	if err := writer.Close(); err != nil {
		return nil, false, false
	}
	return out.Bytes(), true, true
}

// redactValue masks a form field or multipart part. A value holding a
// sensitive value, or one that cannot be parsed as JSON while holding one, is
// masked as a whole.
func (g *graph) redactValue(value []byte, roots []int) ([]byte, bool) {
	if len(g.expand(roots)) == 0 {
		return value, false
	}
	items := g.items(roots)
	if g.sensitive(roots) || g.sensitive(items) && !isJSONStructure(value) {
		return []byte(Mask), true
	}
	// Unencoded text matches a plain string member of the field or of its
	// items when sent as repeated fields, unless it starts like a JSON object
	// or array, which may carry sensitive values.
	if (g.plain(roots, stringShape) || g.plain(items, stringShape)) && !isJSONStructure(value) {
		return value, false
	}
	// A scalar may also be one item of an array sent as repeated fields.
	if !isJSONStructure(value) {
		roots = append(append([]int{}, roots...), items...)
	}
	if masked, changed, ok := g.redactJSON(value, roots); ok {
		return masked, changed
	}
	return []byte(Mask), true
}

// isEncodedPart reports whether a multipart part is transfer or content
// encoded, so that its bytes cannot be read as its value.
func isEncodedPart(header textproto.MIMEHeader) bool {
	switch strings.ToLower(strings.TrimSpace(header.Get("Content-Transfer-Encoding"))) {
	case "", "7bit", "8bit", "binary":
		return header.Get("Content-Encoding") != ""
	}
	return true
}

// hasDuplicateKeys reports whether a JSON object in body repeats a key.
func hasDuplicateKeys(body []byte) bool {
	type object struct {
		keys      map[string]bool
		expectKey bool
	}
	dec := json.NewDecoder(bytes.NewReader(body))
	dec.UseNumber()
	var stack []*object
	for {
		token, err := dec.Token()
		if err != nil {
			return false
		}
		switch t := token.(type) {
		case json.Delim:
			switch t {
			case '{':
				stack = append(stack, &object{keys: map[string]bool{}, expectKey: true})
				continue
			case '[':
				stack = append(stack, nil)
				continue
			}
			stack = stack[:len(stack)-1]
		case string:
			if n := len(stack); n > 0 && stack[n-1] != nil && stack[n-1].expectKey {
				if stack[n-1].keys[t] {
					return true
				}
				stack[n-1].keys[t] = true
				stack[n-1].expectKey = false
				continue
			}
		}
		if n := len(stack); n > 0 && stack[n-1] != nil {
			stack[n-1].expectKey = true
		}
	}
}

func isJSONStructure(value []byte) bool {
	trimmed := bytes.TrimLeft(value, " \t\r\n")
	return len(trimmed) > 0 && (trimmed[0] == '{' || trimmed[0] == '[')
}

func (g *graph) mask(value any, roots []int, depth int) (any, bool) {
	roots = g.expand(roots)
	if len(roots) == 0 {
		return value, false
	}
	if g.sensitive(roots) {
		return Mask, true
	}
	if depth >= maxDepth {
		return Mask, true
	}
	// A value that does not have the shape of its schema cannot be followed
	// to its sensitive values, so it is masked as a whole.
	changed := false
	switch v := value.(type) {
	case nil:
	case map[string]any:
		if !g.hasProperties(roots) {
			return g.mismatch(value, roots, objectShape)
		}
		for key, child := range v {
			if masked, ok := g.mask(child, g.child(roots, key), depth+1); ok {
				v[key] = masked
				changed = true
			}
		}
	case []any:
		items := g.items(roots)
		if len(items) == 0 {
			return g.mismatch(value, roots, arrayShape)
		}
		for i, child := range v {
			if masked, ok := g.mask(child, items, depth+1); ok {
				v[i] = masked
				changed = true
			}
		}
	case string:
		return g.mismatch(value, roots, stringShape)
	case json.Number, float64:
		return g.mismatch(value, roots, numberShape)
	case bool:
		return g.mismatch(value, roots, booleanShape)
	default:
		return Mask, true
	}
	return value, changed
}

// mismatch masks a value that does not have the shape of roots, unless a
// union member of its shape holding nothing sensitive may match it.
func (g *graph) mismatch(value any, roots []int, s shape) (any, bool) {
	if g.plain(roots, s) {
		return value, false
	}
	return Mask, true
}

// plain reports whether any of roots, or their union variants, is a union
// with a member of shape s holding nothing sensitive.
func (g *graph) plain(roots []int, s shape) bool {
	for _, id := range g.expand(roots) {
		if g.nodes[id].plainShape(s) {
			return true
		}
	}
	return false
}

func (n node) plainShape(s shape) bool {
	switch s {
	case objectShape:
		return n.plainObject
	case arrayShape:
		return n.plainArray
	case stringShape:
		return n.plainString
	case numberShape:
		return n.plainNumber
	case booleanShape:
		return n.plainBoolean
	}
	return false
}

// hasProperties reports whether any of roots describes object properties or
// map values.
func (g *graph) hasProperties(roots []int) bool {
	for _, id := range g.expand(roots) {
		if len(g.nodes[id].fields) > 0 || g.nodes[id].values != 0 {
			return true
		}
	}
	return false
}

// sensitive reports whether any of roots, or their union variants, is
// sensitive as a whole.
func (g *graph) sensitive(roots []int) bool {
	for _, id := range g.expand(roots) {
		if g.nodes[id].sensitive {
			return true
		}
	}
	return false
}

// child returns the schemas of the property name of roots.
func (g *graph) child(roots []int, name string) []int {
	var children []int
	for _, id := range g.expand(roots) {
		n := g.nodes[id]
		childID, declared := n.fields[name]
		if !declared {
			childID = n.values
		}
		if childID != 0 {
			children = append(children, childID)
		}
	}
	return children
}

// field returns the schemas of a form field or multipart part of roots. In
// each schema, a name ending in [] that is not declared as such names an
// array sent as repeated fields.
func (g *graph) field(roots []int, name string) []int {
	trimmed, bracketed := strings.CutSuffix(name, "[]")
	var children []int
	for _, id := range g.expand(roots) {
		n := g.nodes[id]
		childID, declared := n.fields[name]
		if !declared && bracketed {
			childID, declared = n.fields[trimmed]
		}
		if !declared {
			childID = n.values
		}
		if childID != 0 {
			children = append(children, childID)
		}
	}
	return children
}

// items returns the array item schemas of roots.
func (g *graph) items(roots []int) []int {
	var items []int
	for _, id := range g.expand(roots) {
		if item := g.nodes[id].item; item != 0 {
			items = append(items, item)
		}
	}
	return items
}

// expand adds the union variants of roots, since the variant a value matches
// is not known.
func (g *graph) expand(roots []int) []int {
	var expanded []int
	seen := make(map[int]bool)
	var visit func(int)
	visit = func(id int) {
		if id <= 0 || id >= len(g.nodes) || seen[id] {
			return
		}
		seen[id] = true
		expanded = append(expanded, id)
		for _, variant := range g.nodes[id].variants {
			visit(variant)
		}
	}
	for _, id := range roots {
		visit(id)
	}
	return expanded
}

