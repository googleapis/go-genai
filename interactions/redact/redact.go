// Package redact masks values marked sensitive in the API description
// (x-speakeasy-param-sensitive or format: password) in HTTP bodies, so that
// HTTP clients and transports can log requests and responses safely.
//
// The SDK attaches the operation ID to the context of each request whose
// operation has sensitive request or response values. A transport reads it
// back from the request, or from a response's Request, to select the schema
// graph used for masking:
//
//	body = redact.RequestBody(req.Context(), req.Header.Get("Content-Type"), body)
//	body = redact.ResponseBody(res.Request.Context(), res.Header.Get("Content-Type"), body)
//
// JSON, application/x-www-form-urlencoded and multipart/form-data bodies are
// masked value by value. Other bodies of an operation with sensitive values are
// masked as a whole.
package redact

